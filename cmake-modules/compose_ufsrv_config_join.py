JOINED_KEYMAP_FNAME = "data_ufsrv_config_literal_to_field_map_priv_generated.h"


def join_keymap(lib_names: List[str], gen_dirs: List[str], output_dir: str,
                literal_map: Dict[str, str]) -> None:
    """
    Join per-library key-map files.
    Each has:
        #define UFSRV_CONFIG_KEY_MAP_COUNT  N
        static const UfsrvConfigKeyMapEntry
        ufsrv_config_key_map[N] = { ... };
    We concatenate the array entries, sort them by their resolved literal
    string (strcmp order — the bsearch() invariant), and update the COUNT.

    Per-library key-maps are only individually sorted, so a naive
    concatenation breaks the bsearch() precondition.  Resolving each
    CONF_FILE_LITERAL_* macro to its string value lets us merge the blocks
    into global strcmp order.
    """
    # (raw_entry_text, resolved_literal_string) — sorted by the string value.
    entries = []
    total_count = 0
    first_content = None

    for gen_dir in gen_dirs:
        path = os.path.join(gen_dir, JOINED_KEYMAP_FNAME)
        if not os.path.exists(path):
            print(f"  WARNING: key-map not found: {path}", file=sys.stderr)
            continue
        content = read_file(path)
        if first_content is None:
            first_content = content

        # Count entries from this library
        cm = re.search(r'#define\s+UFSRV_CONFIG_KEY_MAP_COUNT\s+(\d+)', content)
        if cm:
            total_count += int(cm.group(1))

        # Extract individual entries (raw text + resolved literal) from the body
        body = extract_designated_array(content, "ufsrv_config_key_map")
        if body:
            for m in re.finditer(r'(\s*\{\s*CONF_FILE_LITERAL_(\w+)\s*,\s*UFSRV_CONFIG_FIELD_\w+\s*\},?)', body):
                raw_entry = m.group(1).rstrip(',').rstrip()
                literal_macro = "CONF_FILE_LITERAL_" + m.group(2)
                entries.append((raw_entry, literal_map.get(literal_macro, "")))

    if first_content is None:
        return

    if literal_map:
        unresolved = [raw for raw, key in entries if not key]
        if unresolved:
            print("ERROR: key-map literal(s) unresolved in --literals-header:", file=sys.stderr)
            for raw in unresolved:
                print("    " + raw, file=sys.stderr)
            sys.exit(1)
        entries.sort(key=lambda e: e[1])
        print(f"  key-map: sorted {len(entries)} entries by literal (strcmp order)")
    elif entries:
        print("  WARNING: --literals-header not supplied — key-map NOT globally sorted", file=sys.stderr)

    # Assemble: use first file's structure, replace COUNT and array body
    output = generated_header_comment(
        "data_ufsrv_config_literal_to_field_map_priv_generated.h — joined key-map",
        lib_names)
    output += (
        "#ifndef UFSRV_CORE_UFSRV_CONFIG_DATA_LITERAL_TO_FIELD_MAP_PRIV_GENERATED_H\n"
        "#define UFSRV_CORE_UFSRV_CONFIG_DATA_LITERAL_TO_FIELD_MAP_PRIV_GENERATED_H\n\n"
        "#include <ufsrvcorelib/ufsrv_core/ufsrv_config/generated/ufsrv_config_field_enums_generated.h>\n"
        "#include <ufsrvcorelib/ufsrv_core/configfile_processor/ufsrv_config_literals_defs.h>\n"
        "#include <ufsrvcorelib/ufsrv_core/configfile_processor/ufsrv_config_keymap_entry_type.h>\n\n"
        f"#define UFSRV_CONFIG_KEY_MAP_COUNT  {total_count}\n\n"
        "static const UfsrvConfigKeyMapEntry\n"
        f"ufsrv_config_key_map[{total_count}] = {{\n"
    )
    output += ',\n'.join(raw for raw, _ in entries)
    output += (
        '\n};\n\n'
        "#endif /* UFSRV_CORE_UFSRV_CONFIG_DATA_LITERAL_TO_FIELD_MAP_PRIV_GENERATED_H */\n"
    )

    out_path = os.path.join(output_dir, JOINED_KEYMAP_FNAME)
    output = joined_comment(lib_names, gen_dirs,
                            "data_ufsrv_config_literal_to_field_map_priv_generated.h") + output
    write_file(out_path, output)
    print(f"  joined key-map → {out_path}  ({total_count} entries)")


# ═══════════════════════════════════════════════════════════════════════════════
# 7. Dispatch table — concatenate inside #if 0 block
# ═══════════════════════════════════════════════════════════════════════════════

JOINED_DISPATCH_FNAME = "data_ufsrv_config_dispatch_table_priv_generated.h"


def join_dispatch(lib_names: List[str], gen_dirs: List[str], output_dir: str) -> None:
    """
    Join dispatch tables.  Each file has the table inside #if 0 (preserved,
    not compiled).  We concatenate the entries from all libraries.
    """
    dispatch_entries = []
    first_content = None

    for gen_dir in gen_dirs:
        path = os.path.join(gen_dir, JOINED_DISPATCH_FNAME)
        if not os.path.exists(path):
            print(f"  WARNING: dispatch table not found: {path}", file=sys.stderr)
            continue
        content = read_file(path)
        if first_content is None:
            first_content = content

        # Extract entries from inside #if 0 ... #endif block
        body = extract_designated_array(content, "ufsrv_config_dispatch")
        if body:
            body = body.strip().rstrip(',').strip()
            # Strip trailing sentinel — join adds its own
            body = re.sub(r'\s*\{\s*NULL\s*,\s*-1\s*\}\s*,?\s*$', '', body)
            if body:
                dispatch_entries.append(body)

    if first_content is None:
        return

    joined_body = ',\n'.join(dispatch_entries)

    output = generated_header_comment(
        "DATA_UFSRV_CONFIG_DISPATCH_TABLE_PRIV_GENERATED_H — joined dispatch",
        lib_names)
    output += (
        "#ifndef DATA_UFSRV_CONFIG_DISPATCH_TABLE_PRIV_GENERATED_H\n"
        "#define DATA_UFSRV_CONFIG_DISPATCH_TABLE_PRIV_GENERATED_H\n\n"
        "// Dispatch table — preserved, not compiled\n\n"
        "#if 0\n"
        "// Sorted alphabetically for bsearch.\n"
        "static const struct {\n"
        "    const char *name;\n"
        "    int         enum_index;\n"
        "} ufsrv_config_dispatch[] = {\n"
    )
    if joined_body:
        output += joined_body + ',\n'
    output += (
        "    { NULL, -1 }\n"
        "};\n"
        "#endif\n\n"
        "#endif /* DATA_UFSRV_CONFIG_DISPATCH_TABLE_PRIV_GENERATED_H */\n"
    )

    out_path = os.path.join(output_dir, JOINED_DISPATCH_FNAME)
    output = joined_comment(lib_names, gen_dirs,
                            "data_ufsrv_config_dispatch_table_priv_generated.h") + output
    write_file(out_path, output)
    print(f"  joined dispatch table → {out_path}")


# ═══════════════════════════════════════════════════════════════════════════════
# 8. Master include — regenerate with local include paths
# ═══════════════════════════════════════════════════════════════════════════════

JOINED_MASTER_FNAME = "ufsrv_config_getters_setters_generated.c"


def write_master_include(lib_names: List[str], output_dir: str) -> None:
    """
    Write the master include file that pulls in all composed sources.
    """
    output = generated_header_comment(
        "Master include — pulls in all composed generated source files",
        lib_names)
    output += (
        "#include \"generated/ufsrv_config_field_enums_generated.h\"\n"
        "#include \"generated/ufsrv_config_accessor_decls_generated.h\"\n"
        "#include \"data_ufsrv_config_field_tables_generated.c\"\n"
        "#include \"ufsrv_config_accessor_defs_generated.c\"\n"
        "#include \"ufsrv_config_validate_generated.c\"\n"
    )

    out_path = os.path.join(output_dir, JOINED_MASTER_FNAME)
    # Master include is synthetic — list the libraries, not source files
    lib_list = ', '.join(lib_names)
    output = f"/* JOINED BY ufsrv_config compose from libraries: {lib_list} */\n" + output
    write_file(out_path, output)
    print(f"  master include → {out_path}")


# ═══════════════════════════════════════════════════════════════════════════════
# Main
# ═══════════════════════════════════════════════════════════════════════════════

def main():
    parser = argparse.ArgumentParser(
        description="Join N per-library generated ufsrv_config outputs into a single composed module")
    parser.add_argument('--output', required=True,
                        help='Composed output directory (src/ufsrv_config/)')
    parser.add_argument('--gen-dir', action='append', dest='gen_dirs', default=[],
                        help='Per-library gen dir: lib_name=path (repeatable)')
    parser.add_argument('--literals-header', default=None,
                        help='Path to ufsrv_config_literals_defs.h (macro → string source of truth)')
    args = parser.parse_args()

    if not args.gen_dirs:
        print("ERROR: at least one --gen-dir is required", file=sys.stderr)
        sys.exit(1)

    # Parse --gen-dir into ordered lists
    lib_names = []
    gen_dirs = []
    for item in args.gen_dirs:
        if '=' in item:
            name, path = item.split('=', 1)
        else:
            name = item
            path = item
        lib_names.append(name)
        gen_dirs.append(path)

    output_dir = os.path.abspath(args.output)
    generated_output_dir = os.path.join(output_dir, ENUM_GEN_SUBDIR)

    print(f"compose_ufsrv_config_join: joining {len(lib_names)} libraries → {output_dir}")

    # 1. Join enums (output to generated/ subdir)
    join_enums(lib_names, gen_dirs, output_dir)

    # 2. Join field tables
    join_field_tables(lib_names, gen_dirs, output_dir)

    # 3. Concatenate accessor defs
    concat_verbatim_first_includes(
        lib_names, gen_dirs, JOINED_ACCESSOR_DEFS_FNAME, output_dir,
        "accessor defs")

    # 4. Concatenate accessor decls (to generated/ subdir)
    concat_verbatim_first_includes(
        lib_names, gen_dirs, JOINED_ACCESSOR_DECLS_FNAME, generated_output_dir,
        "accessor decls")

    # 5. Merge validate
    join_validate(lib_names, gen_dirs, output_dir)

    # 6. Join key-map (globally sorted by resolved literal for bsearch)
    literal_map = parse_literals_header(args.literals_header)
    join_keymap(lib_names, gen_dirs, output_dir, literal_map)

    # 7. Join dispatch table
    join_dispatch(lib_names, gen_dirs, output_dir)

    # 8. Write master include
    write_master_include(lib_names, output_dir)

    print(f"compose_ufsrv_config_join: done")


if __name__ == '__main__':
    main()
