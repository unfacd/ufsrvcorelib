#!/usr/bin/env python3
"""
compose_ufsrv_config_join.py — Join N per-library generated outputs into a
single composed src/ufsrv_config/ module.

Invoked from compose_ufsrv_config.cmake when UFSRV_CONFIG_COMPOSER_LIBRARY_NAMES
has more than one entry (N>1).

Usage:
    python3 compose_ufsrv_config_join.py \
        --output <composed_output_dir> \
        --gen-dir <lib_name>=<path_to_generated> ...

The script reads each library's generated files from its staging directory,
joins them by asset type, and writes the unified files into --output.
"""

import argparse
import os
import re
import sys
from typing import List, Tuple, Dict


# ═══════════════════════════════════════════════════════════════════════════════
# Helpers
# ═══════════════════════════════════════════════════════════════════════════════

def read_file(path: str) -> str:
    with open(path, 'r') as f:
        return f.read()


def parse_literals_header(path: str) -> Dict[str, str]:
    """Parse ufsrv_config_literals_defs.h → {macro_name: literal_string}.

    The literals header is the single source of truth for every
    CONF_FILE_LITERAL_* → "dotted.lua.key" spelling.  The key-map join resolves
    each entry's macro here so the merged array can be sorted into global
    strcmp order — the invariant the runtime bsearch() over
    ufsrv_config_key_map[] relies on.
    """
    literals: Dict[str, str] = {}
    if not path or not os.path.exists(path):
        return literals
    for m in re.finditer(r'#define\s+(CONF_FILE_LITERAL_\w+)\s+"([^"]*)"', read_file(path)):
        literals[m.group(1)] = m.group(2)
    return literals


def joined_comment(lib_names: List[str], gen_dirs: List[str], fname: str) -> str:
    """Generate a comment line listing the original source files."""
    lines = ["/* JOINED BY ufsrv_config compose from:"]
    for lib_name, gen_dir in zip(lib_names, gen_dirs):
        src = os.path.join(gen_dir, fname)
        lines.append(f" *   {src}")
    lines.append(" */")
    return '\n'.join(lines) + '\n'


def write_file(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(content)


def generated_header_comment(title: str, lib_names: List[str]) -> str:
    """Standard header for joined generated files."""
    libs = ", ".join(lib_names)
    return (
        "/*\n"
        f" * {title} — COMPOSED, DO NOT EDIT\n"
        " *\n"
        f" * Joined from {len(lib_names)} librar{'ies' if len(lib_names) != 1 else 'y'}: {libs}\n"
        " * Generated by compose_ufsrv_config_join.py at build time.\n"
        " */\n\n"
    )


def extract_braced_block(text: str, keyword: str) -> str:
    """
    Extract a braced block following a keyword like 'enum UfsrvConfigField { ... };'.
    Returns just the content inside the outer braces (no keyword, no trailing '};').
    Handles nested braces.
    """
    # Find the keyword
    idx = text.find(keyword)
    if idx < 0:
        return ""

    # Find opening brace
    brace_idx = text.find('{', idx)
    if brace_idx < 0:
        return ""

    # Count braces to find matching close
    depth = 0
    for i in range(brace_idx, len(text)):
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                return text[brace_idx + 1:i]
    return ""


def strip_count_line(enum_body: str, count_macro: str) -> str:
    """Remove the _COUNT line from an enum body."""
    pattern = re.compile(r'^\s*' + re.escape(count_macro) + r'\s*=\s*\d+\s*,?\s*$', re.MULTILINE)
    result = pattern.sub('', enum_body)
    return result


# ═══════════════════════════════════════════════════════════════════════════════
# 1. Enum joining
# ═══════════════════════════════════════════════════════════════════════════════

JOINED_ENUM_FNAME = "ufsrv_config_field_enums_generated.h"
ENUM_GEN_SUBDIR = "generated"  # headers go in generated/ subdirectory


def join_enums(lib_names: List[str], gen_dirs: List[str], output_dir: str) -> None:
    """
    Join per-library enum headers.
    - CONFIG enum: strip _COUNT from each, concatenate entries, renumber first
      entry of each library sequentially, append single _COUNT at end.
    - RUNTIME enum: same treatment.
    - Output goes to generated/ subdirectory (matching the include-path convention
      ufsrv_config.h expects).
    """
    config_entries: List[str] = []
    runtime_entries: List[str] = []
    config_running = 0
    runtime_running = 0

    for lib_name, gen_dir in zip(lib_names, gen_dirs):
        path = os.path.join(gen_dir, "ufsrv_config_field_enums_generated.h")
        if not os.path.exists(path):
            print(f"  WARNING: enum header not found: {path}", file=sys.stderr)
            continue
        content = read_file(path)

        # ── Config enum ──────────────────────────────────────────────────
        config_block = extract_braced_block(content, "enum UfsrvConfigField")
        if config_block:
            config_block = strip_count_line(config_block, "UFSRV_CONFIG_FIELD_COUNT")
            # Strip trailing comma from last entry, trim whitespace
            config_block = config_block.strip().rstrip(',').strip()
            if config_block:
                # Renumber: set the first entry's value to config_running
                # Pattern: FIELD_NAME = N,  →  FIELD_NAME = config_running,
                lines = config_block.split('\n')
                renumbered = []
                for line in lines:
                    # Replace first "= <number>" with "= <running_idx>"
                    m = re.match(r'^(\s*)([A-Z_][A-Z0-9_]*)\s*=\s*\d+(\s*,?\s*)$', line)
                    if m:
                        renumbered.append(f"{m.group(1)}{m.group(2)} = {config_running}{m.group(3)}")
                        config_running += 1
                    elif re.match(r'^\s*[A-Z_][A-Z0-9_]*\s*,?\s*$', line):
                        # No assignment — auto-increments from previous
                        config_running += 1
                        renumbered.append(line)
                    elif line.strip():
                        renumbered.append(line)
                config_entries.append('\n'.join(renumbered))

        # ── Runtime enum ─────────────────────────────────────────────────
        runtime_block = extract_braced_block(content, "enum UfsrvRuntimeField")
        if runtime_block:
            runtime_block = strip_count_line(runtime_block, "UFSRV_RUNTIME_FIELD_COUNT")
            runtime_block = runtime_block.strip().rstrip(',').strip()
            if runtime_block:
                lines = runtime_block.split('\n')
                renumbered = []
                for line in lines:
                    m = re.match(r'^(\s*)([A-Z_][A-Z0-9_]*)\s*=\s*\d+(\s*,?\s*)$', line)
                    if m:
                        renumbered.append(f"{m.group(1)}{m.group(2)} = {runtime_running}{m.group(3)}")
                        runtime_running += 1
                    elif re.match(r'^\s*[A-Z_][A-Z0-9_]*\s*,?\s*$', line):
                        runtime_running += 1
                        renumbered.append(line)
                    elif line.strip():
                        renumbered.append(line)
                runtime_entries.append('\n'.join(renumbered))

    # ── Assemble joined enum header ───────────────────────────────────────
    config_body = ',\n'.join(config_entries)
    runtime_body = ',\n'.join(runtime_entries)

    output = generated_header_comment(
        "UFSRV_CORE_UFSRV_CONFIG_FIELD_ENUMS_GENERATED_H", lib_names)
    output += (
        "#ifndef UFSRV_CORE_UFSRV_CONFIG_FIELD_ENUMS_GENERATED_H\n"
        "#define UFSRV_CORE_UFSRV_CONFIG_FIELD_ENUMS_GENERATED_H\n\n"
        "// Config field indices\n\n"
        "enum UfsrvConfigField {\n"
    )
    if config_body:
        output += config_body + ',\n'
    output += f"    UFSRV_CONFIG_FIELD_COUNT = {config_running}\n"
    output += "};\n\n"
    output += "// Runtime field indices\n\n"
    output += "enum UfsrvRuntimeField {\n"
    if runtime_body:
        output += runtime_body + ',\n'
    output += f"    UFSRV_RUNTIME_FIELD_COUNT = {runtime_running}\n"
    output += "};\n\n"
    output += "#endif /* UFSRV_CORE_UFSRV_CONFIG_FIELD_ENUMS_GENERATED_H */\n"

    out_path = os.path.join(output_dir, ENUM_GEN_SUBDIR, JOINED_ENUM_FNAME)
    output = joined_comment(lib_names, gen_dirs,
                            "ufsrv_config_field_enums_generated.h") + output
    write_file(out_path, output)
    print(f"  joined enums → {out_path}  (CONFIG={config_running}, RUNTIME={runtime_running})")


