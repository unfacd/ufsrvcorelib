JOINED_ACCESSOR_DEFS_FNAME = "ufsrv_config_accessor_defs_generated.c"
JOINED_ACCESSOR_DECLS_FNAME = "ufsrv_config_accessor_decls_generated.h"


def concat_verbatim_first_includes(
    lib_names: List[str], gen_dirs: List[str],
    fname: str, output_dir: str, label: str
) -> None:
    """
    Concatenate files verbatim.  Header comment from the first file,
    includes collected and deduplicated from all libraries, bodies from
    all libraries appended.
    """
    # Extract header comment from first file
    first_path = os.path.join(gen_dirs[0], fname)
    first_content = read_file(first_path)
    comment_end = first_content.find('*/\n')
    header_comment = first_content[:comment_end + 3] if comment_end >= 0 else ""

    # Collect, rewrite, and deduplicate includes from all libraries
    catalogue_paths = [os.path.join(os.path.dirname(d),
                        "ufsrv_config_generator_fields.c.input") for d in gen_dirs]
    includes = collect_and_rewrite_includes(gen_dirs, fname,
                                            extra_paths=catalogue_paths)

    # Extract guard and body from each file
    bodies = []
    guard_ifndef = ""
    guard_define = ""
    for gen_dir in gen_dirs:
        path = os.path.join(gen_dir, fname)
        if not os.path.exists(path):
            continue
        content = read_file(path)

        # Strip header comment
        body = re.sub(r'/\*.*?\*/\s*', '', content, count=1, flags=re.DOTALL)

        # Capture guard from first file (for .h)
        if fname.endswith('.h') and not guard_ifndef:
            gm = re.search(r'(#ifndef[^\n]*\n)(#define[^\n]*\n)', body)
            if gm:
                guard_ifndef = gm.group(1)
                guard_define = gm.group(2)
                body = body[gm.end():]

        # Strip includes + guard from body
        body = re.sub(r'^#include[^\n]*\n', '', body, flags=re.MULTILINE)
        body = re.sub(r'^#ifndef[^\n]*\n', '', body, flags=re.MULTILINE)
        body = re.sub(r'^#define[^\n]*\n', '', body, flags=re.MULTILINE)
        body = re.sub(r'\n#endif[^\n]*$', '', body)
        body = body.strip()
        if body:
            bodies.append(body)

    # Assemble
    output = header_comment + '\n'
    if guard_ifndef:
        output += guard_ifndef + guard_define
    output += includes + '\n\n'
    output += '\n\n'.join(bodies) + '\n'
    if guard_ifndef:
        guard_name = os.path.basename(fname).upper().replace('.', '_')
        output += f"#endif /* {guard_name} */\n"

    out_path = os.path.join(output_dir, fname)
    output = joined_comment(lib_names, gen_dirs, fname) + output
    write_file(out_path, output)
    print(f"  concatenated {label} → {out_path}")


# ═══════════════════════════════════════════════════════════════════════════════
# 5. Validate merge — join validation blocks into single UfsrvConfigValidate()
# ═══════════════════════════════════════════════════════════════════════════════

JOINED_VALIDATE_FNAME = "ufsrv_config_validate_generated.c"


def join_validate(lib_names: List[str], gen_dirs: List[str], output_dir: str) -> None:
    """
    Merge per-library validate functions.
    Each library generates:
        UfsrvConfigResult
        UfsrvConfigValidate(void)
        {
            // validation blocks...
            UfsrvConfigResult ok = { UFSRV_CONFIG_OK, NULL };
            return ok;
        }
    We take the preamble (includes + function signature + opening brace) from
    the first library, collect all validation blocks, and append a single
    return-OK tail.
    """
    first_path = os.path.join(gen_dirs[0], JOINED_VALIDATE_FNAME)
    if not os.path.exists(first_path):
        print(f"  WARNING: validate not found: {first_path}", file=sys.stderr)
        return
    first_content = read_file(first_path)

    # Extract preamble: everything up to and including the opening brace
    # of UfsrvConfigValidate
    preamble_pattern = re.compile(
        r'(.*?UfsrvConfigValidate\s*\(\s*void\s*\)\s*\n\s*\{)', re.DOTALL)
    preamble_m = preamble_pattern.search(first_content)
    if not preamble_m:
        print(f"  WARNING: cannot parse validate preamble", file=sys.stderr)
        # Fallback: copy first file verbatim
        concat_verbatim_first_includes(
            lib_names, gen_dirs, JOINED_VALIDATE_FNAME, output_dir, "validate")
        return
    preamble = preamble_m.group(1)

    # Collect validation blocks from all libraries
    validation_blocks = []
    for gen_dir in gen_dirs:
        path = os.path.join(gen_dir, JOINED_VALIDATE_FNAME)
        if not os.path.exists(path):
            continue
        content = read_file(path)

        # Extract body: between the opening brace and the "UfsrvConfigResult ok"
        # at the end, inclusive of the per-field validation blocks
        body_start = content.find('{', content.find('UfsrvConfigValidate'))
        if body_start < 0:
            continue

        # Find the final "UfsrvConfigResult ok = ... return ok; }" tail
        tail_pattern = re.compile(
            r'\n(\s*)UfsrvConfigResult\s+ok\s*=\s*\{[^}]+\}\s*;\s*\n\s*return\s+ok\s*;\s*\n\}',
            re.MULTILINE)
        tail_m = tail_pattern.search(content)
        if tail_m:
            body_end = tail_m.start()
        else:
            # Fallback: find last '}'
            body_end = content.rfind('}')
        body = content[body_start + 1:body_end].strip()
        if body:
            validation_blocks.append(body)

    # Assemble
    output = generated_header_comment(
        "ufsrv_config_validate_generated.c — joined validate", lib_names)
    # Replicate includes from first file (before the function)
    includes_m = re.match(r'(/\*.*?\*/\n)?(\s*#include[^\n]*\n)*', first_content, re.DOTALL)
    if includes_m:
        output += includes_m.group(0).rstrip() + '\n\n'
    output += "// Validation\n\n"
    output += preamble + '\n'
    output += '\n'.join(validation_blocks) + '\n'
    output += (
        "    UfsrvConfigResult ok = { UFSRV_CONFIG_OK, NULL };\n"
        "    return ok;\n"
        "}\n"
    )

    out_path = os.path.join(output_dir, JOINED_VALIDATE_FNAME)
    output = joined_comment(lib_names, gen_dirs,
                            JOINED_VALIDATE_FNAME) + output
    write_file(out_path, output)
    print(f"  merged validate → {out_path}")


