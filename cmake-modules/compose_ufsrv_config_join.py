JOINED_TABLES_FNAME = "data_ufsrv_config_field_tables_generated.c"


def extract_designated_array(text: str, array_name: str) -> str:
    """
    Extract the body (elements) of a designated-initializer array:
        static ... array_name[SIZE] = { ... };
    Returns just the content between the outer braces (the element list).
    """
    # Find array declaration
    pattern = re.compile(
        r'(?:static\s+)?(?:const\s+)?.+?\s+' + re.escape(array_name) +
        r'\s*\[[^\]]*\]\s*=\s*\{', re.DOTALL)
    m = pattern.search(text)
    if not m:
        return ""

    start = m.end() - 1  # position of the opening '{'
    depth = 0
    for i in range(start, len(text)):
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    return ""


def extract_includes_preamble(text: str) -> str:
    """Extract everything before the first 'static' declaration."""
    static_idx = text.find('\nstatic ')
    if static_idx < 0:
        # Try finding before comment markers
        static_idx = text.find('\n// ── ')
    if static_idx < 0:
        return ""
    return text[:static_idx + 1]


# Mapping of include-paths that must be rewritten for the flat composed layout.
# Key is the path as it appears in the angle brackets / quotes.
# Value is the rewritten path.
_COMPOSED_INCLUDE_REWRITE = {
    # Generated headers move to the flat generated/ subdirectory (quoted)
    "ufsrv_config_field_enums_generated.h":     "generated/ufsrv_config_field_enums_generated.h",
    "ufsrv_config_accessor_decls_generated.h":  "generated/ufsrv_config_accessor_decls_generated.h",
    # configfile_processor types are local in the composed module
    "ufsrv_config_keymap_entry_type.h":         "ufsrv_config_keymap_entry_type.h",
    "ufsrv_config_literals_defs.h":             "ufsrv_config_literals_defs.h",
    # ufsrv_config type headers — owned by ufsrvcorelib;
    # ufnetcorelib's generator prepends ufnetcorelib/, rewrite to canonical
    "ufsrv_config.h":                           "ufsrvcorelib/ufsrv_core/ufsrv_config/ufsrv_config.h",
    "ufsrv_config_types.h":                     "ufsrvcorelib/ufsrv_core/ufsrv_config/ufsrv_config_types.h",
    "ufsrv_config_value_type.h":                "ufsrvcorelib/ufsrv_core/ufsrv_config/ufsrv_config_value_type.h",
    "ufsrv_config_store_operating_state_enum.h": "ufsrvcorelib/ufsrv_core/ufsrv_config/ufsrv_config_store_operating_state_enum.h",
    "ufsrv_config_field_descriptor.h":          "ufsrvcorelib/ufsrv_core/ufsrv_config/ufsrv_config_field_descriptor.h",
    # ufsrvcorelib top-level defs
    "ufsrvcorelib_defs.h":                      "ufsrvcorelib/ufsrvcorelib_defs.h",
}


def _rewrite_include(line: str) -> str:
    """Rewrite a single #include line using the fixed map.  Unmapped paths
    are returned unchanged."""
    # Extract the path from inside angle brackets or double quotes
    m = re.match(r'#include\s+[<"]([^>"]+)[>"]', line)
    if not m:
        return line
    path = m.group(1)
    # Strip any library prefix to get the filename (last component)
    basename = os.path.basename(path)
    if basename in _COMPOSED_INCLUDE_REWRITE:
        new_path = _COMPOSED_INCLUDE_REWRITE[basename]
        if new_path == path:
            return line  # already correct
        # generated/ paths are local → quotes; everything else → angle brackets
        if new_path.startswith('generated/'):
            return f'#include "{new_path}"'
        else:
            return f'#include <{new_path}>'
    return line


def collect_and_rewrite_includes(gen_dirs: List[str], fname: str,
                                 extra_paths: List[str] = None) -> str:
    """Collect #include lines from generated files and optional extra sources.
    Rewrite what is in the map, deduplicate, return the unified block."""
    seen = set()
    lines = []
    paths = [os.path.join(d, fname) for d in gen_dirs]
    if extra_paths:
        paths.extend(extra_paths)
    for path in paths:
        if not os.path.exists(path):
            continue
        for line in read_file(path).split('\n'):
            if line.strip().startswith('#include '):
                rewritten = _rewrite_include(line)
                s = rewritten.strip()
                if s not in seen:
                    seen.add(s)
                    lines.append(rewritten)
    return '\n'.join(lines)


def join_field_tables(lib_names: List[str], gen_dirs: List[str], output_dir: str) -> None:
    """
    Join field table files at the element level.
    Each library has:
      - ufsrv_config_field_table[]       (CONFIG entries)
      - ufsrv_runtime_field_table[]      (RUNTIME entries)
      - ufsrv_config_field_defaults_table[]  (CONFIG defaults)
      - ufsrv_runtime_field_defaults_table[] (RUNTIME defaults)
    Extract elements from each, concatenate, wrap in single arrays.
    """
    config_field_entries = []
    runtime_field_entries = []
    config_default_entries = []
    runtime_default_entries = []

    for gen_dir in gen_dirs:
        path = os.path.join(gen_dir, JOINED_TABLES_FNAME)
        if not os.path.exists(path):
            print(f"  WARNING: field tables not found: {path}", file=sys.stderr)
            continue
        content = read_file(path)

        for array_name, collector in [
            ("ufsrv_config_field_table", config_field_entries),
            ("ufsrv_runtime_field_table", runtime_field_entries),
            ("ufsrv_config_field_defaults_table", config_default_entries),
            ("ufsrv_runtime_field_defaults_table", runtime_default_entries),
        ]:
            body = extract_designated_array(content, array_name)
            if body:
                body = body.strip().rstrip(',').strip()
                if body:
                    collector.append(body)

    # Get COUNTs from joined enums
    enum_path = os.path.join(output_dir, ENUM_GEN_SUBDIR, JOINED_ENUM_FNAME)
    config_count = 0
    runtime_count = 0
    if os.path.exists(enum_path):
        enum_content = read_file(enum_path)
        cm = re.search(r'UFSRV_CONFIG_FIELD_COUNT\s*=\s*(\d+)', enum_content)
        rm = re.search(r'UFSRV_RUNTIME_FIELD_COUNT\s*=\s*(\d+)', enum_content)
        if cm:
            config_count = int(cm.group(1))
        if rm:
            runtime_count = int(rm.group(1))

    catalogue_paths = [os.path.join(os.path.dirname(d),
                        "ufsrv_config_generator_fields.c.input") for d in gen_dirs]
    includes = collect_and_rewrite_includes(gen_dirs, JOINED_TABLES_FNAME,
                                            extra_paths=catalogue_paths)

    output = generated_header_comment(
        "data_ufsrv_config_field_tables_generated.c — joined field tables", lib_names)
    output += includes.rstrip() + '\n\n'

    # Config field table
    output += "// ── Config field table — indexed by enum UfsrvConfigField\n\n"
    output += "static UfsrvConfigFieldEntry\n"
    output += f"ufsrv_config_field_table[{config_count}] = {{\n"
    output += ',\n'.join(config_field_entries)
    output += '\n};\n\n'

    # Runtime field table
    output += "// ── Runtime field table — indexed by enum UfsrvRuntimeField\n\n"
    output += "static UfsrvConfigFieldEntry\n"
    output += f"ufsrv_runtime_field_table[{runtime_count}] = {{\n"
    output += ',\n'.join(runtime_field_entries)
    output += '\n};\n\n'

    # Config defaults
    output += "// ── Config field compiled defaults — indexed by enum UfsrvConfigField\n\n"
    output += "static const UfsrvConfigValue\n"
    output += f"ufsrv_config_field_defaults_table[{config_count}] = {{\n"
    output += ',\n'.join(config_default_entries)
    output += '\n};\n\n'

    # Runtime defaults
    output += "// ── Runtime field compiled defaults — indexed by enum UfsrvRuntimeField\n\n"
    output += "static const UfsrvConfigValue\n"
    output += f"ufsrv_runtime_field_defaults_table[{runtime_count}] = {{\n"
    output += ',\n'.join(runtime_default_entries)
    output += '\n};\n'

    out_path = os.path.join(output_dir, JOINED_TABLES_FNAME)
    output = joined_comment(lib_names, gen_dirs,
                            JOINED_TABLES_FNAME) + output
    write_file(out_path, output)
    print(f"  joined field tables → {out_path}")


