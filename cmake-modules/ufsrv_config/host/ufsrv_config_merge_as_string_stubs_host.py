#!/usr/bin/env python3
"""
Merge the per-library ufsrv_config_stubs_as_string_priv.h headers into a single
local ufsrv_config_stubs_as_string_priv_generated.h for the ufsrvwebsock deep
tree.

Each composed library (ufsrvcorelib, ufnetcorelib) ships a hand-maintained
ufsrv_config_stubs_as_string_priv.h declaring the non-standard AsString
marshallers for ITS OWN fields.  The merged output is emitted under a "_generated"
name so it never overwrites a hand-maintained ufsrv_config_stubs_as_string_priv.h;
the consumer reconciles the two.  The per-library headers are merged by stripping
their individual #ifndef guards and deduplicating the (identical) #include lines,
then re-emitting everything under one guard with a provenance comment listing the
merged source paths.

Usage:
  python3 ufsrv_config_merge_as_string_stubs_host.py --output <merged.h> <src1> [<src2> ...]
"""
import os
import sys

GUARD = "UFSRV_CONFIG_STUBS_AS_STRING_PRIV_GENERATED_H"


def split_body(text):
    """Return (includes, decls) from a stub priv header.

    Includes are collected once (deduped by the caller); decls are the AsString
    function prototypes.  Guard lines, comment lines and blanks are dropped.
    """
    includes = []
    decls = []
    for raw in text.splitlines():
        s = raw.strip()
        if s.startswith("#include"):
            includes.append(s)
        elif "AsString" in s and "(" in s:
            decls.append(s)
        # everything else (#ifndef/#define/#endif, comments, blanks) is dropped
    return includes, decls


def main(argv):
    if len(argv) < 4 or argv[1] != "--output":
        sys.stderr.write("usage: %s --output <merged.h> <src1> [<src2> ...]\n" % argv[0])
        return 2

    out_path = argv[2]
    src_paths = argv[3:]

    all_includes = []
    seen_includes = set()
    blocks = []

    for path in src_paths:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        includes, decls = split_body(text)
        for inc in includes:
            if inc not in seen_includes:
                seen_includes.add(inc)
                all_includes.append(inc)
        blocks.append((path, decls))

    lines = [
        "/*",
        " * %s — MERGED by ufsrv_config_compose_host." % os.path.basename(out_path),
        " * DO NOT EDIT — regenerated by the ufsrv_config_compose_host target.",
        " *",
        " * Merge of the following library headers:",
    ]
    for path, _ in blocks:
        lines.append(" *   - %s" % path)
    lines.append(" */")
    lines.append("#ifndef %s" % GUARD)
    lines.append("#define %s" % GUARD)
    lines.append("")
    lines.extend(all_includes)
    lines.append("")
    for path, decls in blocks:
        lines.append("/* === from: %s ===" % path)
        lines.append(" */")
        lines.extend(decls)
        lines.append("")
    lines.append("#endif /* %s */" % GUARD)
    lines.append("")

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print("ufsrv_config_merge_as_string_stubs_host: merged %d header(s) → %s (%d decls)"
          % (len(blocks), out_path, sum(len(d) for _, d in blocks)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
